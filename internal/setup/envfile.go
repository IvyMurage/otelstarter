// renderEnvFile builds otel.env. It uses only standard OpenTelemetry
// environment variables, so the file works with any OpenTelemetry SDK,
// Docker's env_file and Kubernetes, without otelstarter installed.
func renderEnvFile(service string, languageVars []project.EnvVar) []byte {
	vars := []project.EnvVar{
		{Name: "OTEL_SERVICE_NAME", Value: service,
			Comment: "Name shown for this service in traces, metrics and logs."},
		{Name: "OTEL_RESOURCE_ATTRIBUTES", Value: "deployment.environment.name=local",
			Comment: "Where this service runs. Change it for staging or production."},
		{Name: "OTEL_EXPORTER_OTLP_ENDPOINT", Value: "http://localhost:4318",
			Comment: "The OpenTelemetry Collector that receives the telemetry."},
		{Name: "OTEL_EXPORTER_OTLP_PROTOCOL", Value: "http/protobuf",
			Comment: "Send over HTTP, matching the exporter otelstarter installs."},
	}
	vars = append(vars, languageVars...)

	var b strings.Builder
	b.WriteString("# OpenTelemetry settings, generated by otelstarter.\n")
	b.WriteString("# Load them before starting your app:\n")
	b.WriteString("#   set -a && . ./" + EnvFileName + " && set +a\n")
	b.WriteString("# This file is meant to be committed. Never put secrets such as API keys in it.\n")
	for _, v := range vars {
		b.WriteString("\n# " + v.Comment + "\n")
		b.WriteString(v.Name + "=" + v.Value + "\n")
	}
	return []byte(b.String())
}

// serviceName returns the first candidate that is non-empty once made safe,
// or "app". Only lowercase letters, digits, '.', '_' and '-' are kept; any
// other character, including spaces and newlines, becomes '-'. That also
// stops a crafted project name from adding extra lines to otel.env.
func serviceName(candidates ...string) string {
	for _, c := range candidates {
		if name := sanitizeServiceName(c); name != "" {
			return name
		}
	}
	return "app"
}

func sanitizeServiceName(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '.', r == '_', r == '-':
			b.WriteRune(r)
		default:
			b.WriteRune('-')
		}
	}
	// Collapse runs of '-' and trim them from the ends.
	parts := strings.FieldsFunc(b.String(), func(r rune) bool { return r == '-' })
	return strings.Join(parts, "-")
}
